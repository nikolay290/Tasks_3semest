#pragma once

#include <cstddef>
#include <memory>
#include <string>
#include <vector>

namespace miit::algebra {

    class Generator;

    /**
     * @brief Универсальный класс матрицы (двумерного массива)
     * @tparam T Тип элементов матрицы
     *
     * Этот заголовочный файл (вместе с Matrix.cpp) не имеет зависимостей
     * от остальной части решения (никаких классов задач) и может быть
     * без изменений скопирован в любой другой проект.
     */
    template <typename T>
    class Matrix {
    private:
        /**
         * @brief Количество строк в матрице
         */
        size_t rows;

        /**
         * @brief Количество столбцов в матрице
         */
        size_t cols;

        /**
         * @brief Данные матрицы — вектор строк, каждая строка - вектор из cols элементов
         */
        std::vector<std::vector<T>> data;

    public:
        /**
         * @brief Конструктор по умолчанию. Создаёт пустую матрицу размером 0x0
         */
        Matrix();

        /**
         * @brief Конструктор с заданным размером
         * @param rows количество строк
         * @param cols количество столбцов
         * @note элементы инициализируются значением по умолчанию (T())
         */
        Matrix(const size_t rows, const size_t cols);

        /**
         * @brief Конструктор копирования
         * @param other матрица, которую нужно скопировать
         */
        Matrix(const Matrix& other) = default;

        /**
         * @brief Конструктор перемещения
         * @param other матрица, содержимое которой перемещается
         */
        Matrix(Matrix&& other) noexcept;

        /**
         * @brief Оператор копирующего присваивания
         * @param other матрица, которую нужно скопировать
         * @return ссылка на текущий объект
         */
        Matrix& operator=(const Matrix& other) = default;

        /**
         * @brief Оператор перемещающего присваивания
         * @param other матрица, содержимое которой перемещается
         * @return ссылка на текущий объект
         */
        Matrix& operator=(Matrix&& other) noexcept;

        /**
         * @brief Деструктор по умолчанию
         */
        ~Matrix() = default;

        // ============================================================
        // Методы доступа к информации о матрице
        // ============================================================

        /**
         * @brief Получить количество строк в матрице
         * @return Количество строк
         */
        size_t getRows() const;

        /**
         * @brief Получить количество столбцов в матрице
         * @return Количество столбцов
         */
        size_t getCols() const;

        /**
         * @brief Проверить, пустая ли матрица
         * @return true если матрица пустая, иначе false
         */
        bool isEmpty() const;

        // ============================================================
        // Методы доступа к элементам
        // ============================================================

        /**
         * @brief Доступ к строке матрицы по индексу (неконстантный)
         * @param index Индекс строки
         * @return Ссылка на вектор строки
         */
        std::vector<T>& operator[](const size_t index);

        /**
         * @brief Доступ к строке матрицы по индексу (константный)
         * @param index Индекс строки
         * @return Константная ссылка на вектор строки
         */
        const std::vector<T>& operator[](const size_t index) const;

        // ============================================================
        // Операторы сдвига
        // ============================================================

        /**
         * @brief Оператор циклического сдвига строк влево
         * @param positions количество позиций сдвига
         * @return новая матрица со сдвинутыми строками
         */
        Matrix operator<<(const size_t positions) const;

        /**
         * @brief Оператор циклического сдвига строк вправо
         * @param positions количество позиций сдвига
         * @return новая матрица со сдвинутыми строками
         */
        Matrix operator>>(const size_t positions) const;

        // ============================================================
        // Методы изменения размера
        // ============================================================

        /**
         * @brief Изменить размер матрицы
         * @param newRows Новое количество строк
         * @param newCols Новое количество столбцов
         * @note При увеличении размера новые элементы инициализируются значением по умолчанию
         * @note При уменьшении размера лишние элементы отбрасываются
         */
        void resize(const size_t newRows, const size_t newCols);

        /**
         * @brief Очистить матрицу (установить размер 0x0)
         */
        void clear();

        // ============================================================
        // Методы заполнения
        // ============================================================

        /**
         * @brief Заполнить всю матрицу заданным значением
         * @param value Значение для заполнения
         */
        void fill(const T& value);

        /**
         * @brief Заполнить матрицу значениями из генератора
         * @param generator Генератор значений
         */
        void fill(Generator& generator);

        // ============================================================
        // Задания варианта 3
        // ============================================================

        /**
         * @brief Заменить все элементы первых трех столбцов на их квадраты
         */
        void replaceFirstThreeColumnsWithSquares();

        /**
         * @brief Вставить после каждой нечетной строки копию первой строки
         * @return Новая матрица с вставленными строками
         */
        Matrix insertFirstRowAfterOddRows() const;

        // ============================================================
        // Методы вывода
        // ============================================================

        /**
         * @brief Преобразовать матрицу в строку
         * @return Строковое представление матрицы
         */
        std::string toString() const;

        // ============================================================
        // Методы копирования
        // ============================================================

        /**
         * @brief Создать копию матрицы
         * @return Умный указатель на копию матрицы
         */
        std::unique_ptr<Matrix<T>> clone() const;
    };

} // namespace miit::algebra