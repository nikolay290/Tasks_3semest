#pragma once
//
// FormatUtils.h
// Небольшие вспомогательные функции форматирования строк. Не являются
// классом предметной области, поэтому не подпадают под правило "каждый
// класс - в своей паре файлов", но, как и весь остальной код библиотеки,
// не используют потоки ввода-вывода (<iostream>/<fstream>/<sstream>/
// <cstdio>) - только std::string и арифметику.
//
#include <string>
#include <vector>

namespace FormatUtils {

    /**
     * @brief Форматирует дробное число с ровно двумя знаками после
     *        точки (например, 123.5 -> "123.50"), без использования
     *        потоков ввода-вывода. Используется для средних баллов.
     * @param value Значение для форматирования.
     * @return Отформатированная строка.
     */
    std::string FormatDecimal(const double value);

    /**
     * @brief Регистронезависимое сравнение двух строк в кодировке UTF-8.
     *        Корректно работает как с латиницей (A-Z/a-z), так и с
     *        кириллицей (А-Я/а-я, Ё/ё) - декодирует обе строки
     *        посимвольно (по кодовым точкам Unicode) и сравнивает их в
     *        нижнем регистре. Требует, чтобы исходные файлы
     *        компилировались как UTF-8 (см. флаг /utf-8 в настройках
     *        проектов), иначе байты std::string не совпадут с текстом
     *        исходников.
     * @param a Первая строка для сравнения.
     * @param b Вторая строка для сравнения.
     * @return true, если @p a и @p b равны без учёта регистра букв.
     */
    bool EqualsIgnoreCase(const std::string& a, const std::string& b);

    /**
     * @brief Проверяет, содержит ли @p haystack подстроку @p needle
     *        (регистронезависимо, в кодировке UTF-8). Используется для
     *        поиска студента по ФИО при вводе части имени.
     * @param haystack Строка, в которой ищем.
     * @param needle   Искомая подстрока; пустая строка всегда найдена.
     * @return true, если @p needle входит в @p haystack.
     */
    bool ContainsIgnoreCase(const std::string& haystack, const std::string& needle);

    /**
     * @brief Приводит строку к виду "Фамилия И. О.": фамилия остаётся
     *        целиком, каждая следующая часть имени сокращается до первой
     *        буквы с точкой (например, "Иванов Иван Иванович" ->
     *        "Иванов И. И."). Лишние пробелы игнорируются.
     * @param fullName Полное ФИО.
     * @return Сокращённое представление ФИО.
     */
    std::string ToInitials(const std::string& fullName);

    /**
     * @brief Убирает пробелы в начале и в конце строки.
     * @param text Исходная строка.
     * @return Строка без крайних пробелов.
     */
    std::string Trim(const std::string& text);

    /**
     * @brief Склеивает элементы коллекции в одну строку через разделитель.
     * @param items     Элементы для склейки.
     * @param separator Разделитель между элементами.
     * @return Объединённая строка; для пустой коллекции - пустая строка.
     */
    std::string Join(const std::vector<std::string>& items, const std::string& separator);
}
